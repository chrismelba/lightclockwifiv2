"""Generate h/assets.h from the files in web/.

Every static asset the clock serves lives in web/ as a normal, editable file.
This script is run by PlatformIO before each build (extra_scripts in
platformio.ini), so the PROGMEM copies can never drift from the sources the
way the old hand-pasted h/*.h headers did.

Text assets are stored gzip-compressed and served with Content-Encoding: gzip,
which is roughly a 70% saving on both flash and wire. Already-compressed
formats (woff2) are stored raw when gzip fails to earn its keep.
"""

import gzip
import os
import re

def _project_root():
    """Locate the project root whether run standalone or as a PlatformIO extra_script.

    PlatformIO exec()s this file, so __file__ is not defined in that context;
    it exports an SCons `env` carrying PROJECT_DIR instead.
    """
    try:
        Import("env")  # noqa: F821 -- injected by SCons
        return env["PROJECT_DIR"]  # noqa: F821
    except Exception:
        return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


ROOT = _project_root()
WEB_DIR = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "h", "assets.h")

MIME = {
    ".css": "text/css",
    ".js": "application/javascript",
    ".woff2": "font/woff2",
    ".html": "text/html",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
}

# Only worth gzipping if it saves at least this fraction.
MIN_GAIN = 0.05


def symbol(name):
    return "asset_" + re.sub(r"[^0-9a-zA-Z]", "_", name)


def emit_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("  " + ",".join("0x%02x" % b for b in bytearray(chunk)) + ",")
    return "\n".join(lines)


def build():
    if not os.path.isdir(WEB_DIR):
        raise SystemExit("build_assets: missing web/ directory at %s" % WEB_DIR)

    names = sorted(n for n in os.listdir(WEB_DIR) if not n.startswith("."))
    if not names:
        raise SystemExit("build_assets: web/ is empty")

    out = [
        "// GENERATED BY tools/build_assets.py -- DO NOT EDIT.",
        "// Edit the files in web/ instead; this header is rebuilt on every compile.",
        "#pragma once",
        "",
        "struct WebAsset {",
        "  const char* path;",
        "  const char* mime;",
        "  const uint8_t* data;",
        "  size_t len;",
        "  bool gzipped;",
        "};",
        "",
    ]
    table = []
    total_raw = total_stored = 0

    for name in names:
        ext = os.path.splitext(name)[1].lower()
        if ext not in MIME:
            print("build_assets: skipping %s (unknown type)" % name)
            continue

        with open(os.path.join(WEB_DIR, name), "rb") as fh:
            raw = fh.read()

        # mtime=0 keeps the output byte-identical across rebuilds.
        buf = gzip.compress(raw, 9, mtime=0) if hasattr(gzip, "compress") else None
        gzipped = buf is not None and len(buf) < len(raw) * (1.0 - MIN_GAIN)
        data = buf if gzipped else raw

        sym = symbol(name)
        out.append("static const uint8_t %s[] PROGMEM = {" % sym)
        out.append(emit_bytes(data))
        out.append("};")
        out.append("")
        table.append('  {"/%s", "%s", %s, %d, %s},'
                     % (name, MIME[ext], sym, len(data), "true" if gzipped else "false"))

        total_raw += len(raw)
        total_stored += len(data)
        print("build_assets: %-22s %6d -> %6d B  %s"
              % (name, len(raw), len(data), "gzip" if gzipped else "raw"))

    out.append("static const WebAsset webAssets[] PROGMEM = {")
    out.extend(table)
    out.append("};")
    out.append("static const size_t webAssetCount = %d;" % len(table))
    out.append("")

    print("build_assets: %d assets, %d -> %d bytes of flash (%d%% saved)"
          % (len(table), total_raw, total_stored,
             100 - (total_stored * 100 // max(total_raw, 1))))

    text = "\n".join(out)
    # Avoid touching the file when unchanged so PlatformIO doesn't rebuild the world.
    if os.path.exists(OUT):
        with open(OUT) as fh:
            if fh.read() == text:
                return
    with open(OUT, "w") as fh:
        fh.write(text)


build()
